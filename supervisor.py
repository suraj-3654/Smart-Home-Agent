import os
from typing import List, Literal
from pydantic import BaseModel, Field
from dotenv import load_dotenv
from langchain_groq import ChatGroq

# Import sub-agents
from sub_agents import run_lighting_agent, run_climate_agent, run_security_agent

# Import actual tool functions and shared state manager
from tools import control_light, set_thermostat, control_door_lock, get_home_status, home_manager

load_dotenv()

# -------------------------------------------------------------------
# 1. DEFINE STRUCTURED ROUTING SCHEMAS
# -------------------------------------------------------------------

class AgentTask(BaseModel):
    """Represents a single sub-task delegated to a specialized sub-agent."""
    agent: Literal["lighting", "climate", "security"] = Field(
        description="The specialized sub-agent that should handle this task."
    )
    task: str = Field(
        description="The detailed instruction or prompt for the sub-agent."
    )

class RoutingPlan(BaseModel):
    """The complete execution plan generated by the Supervisor."""
    tasks: List[AgentTask] = Field(
        description="List of tasks to be executed by sub-agents."
    )


# Map function names (as strings) to actual callable Python function objects
TOOL_MAP = {
    "control_light": control_light,
    "set_thermostat": set_thermostat,
    "control_door_lock": control_door_lock,
    "get_home_status": get_home_status
}


# -------------------------------------------------------------------
# 2. INITIALIZE SUPERVISOR LLM
# -------------------------------------------------------------------

llm = ChatGroq(
    model="openai/gpt-oss-20b",
    temperature=0
)

supervisor_router = llm.with_structured_output(RoutingPlan)

SYSTEM_PROMPT = """You are the Smart Home Supervisor Agent.
Your job is to analyze user requests and decompose them into actionable sub-tasks for our specialized sub-agents:

1. 'lighting': Handles lights, brightness, and ambient lighting requests.
2. 'climate': Handles thermostat, target temperature, heating, and cooling requests.
3. 'security': Handles smart locks and door security.

Guidelines:
- If a user prompt contains multiple requests, create separate tasks for each relevant agent.
- Make each sub-task clear and concise for the target agent.
"""


# -------------------------------------------------------------------
# 3. TOOL EXECUTION HELPER
# -------------------------------------------------------------------

def execute_tool_calls(tool_calls: list) -> list:
    """
    Takes raw tool_calls from an agent, looks up the corresponding Python
    function in TOOL_MAP, executes it, and returns the execution outputs.
    """
    results = []
    for call in tool_calls:
        tool_name = call["name"]
        tool_args = call["args"]
        
        print(f"   [Executing Tool] '{tool_name}' with args: {tool_args}")
        
        if tool_name in TOOL_MAP:
            # Invoke the LangChain tool with extracted arguments
            tool_func = TOOL_MAP[tool_name]
            execution_output = tool_func.invoke(tool_args)
            results.append({
                "tool_name": tool_name,
                "result": execution_output
            })
        else:
            results.append({
                "tool_name": tool_name,
                "error": f"Tool '{tool_name}' not recognized in TOOL_MAP."
            })
            
    return results


# -------------------------------------------------------------------
# 4. FULL ORCHESTRATION WORKFLOW
# -------------------------------------------------------------------

def orchestrate_request(user_input: str):
    """
    End-to-End Orchestration Loop:
    1. Supervisor generates RoutingPlan.
    2. Sub-agents generate tool call requests.
    3. Tool Execution Handler runs functions against SmartHomeDeviceManager.
    4. Returns overall status and updated home state.
    """
    print(f"\n==========================================")
    print(f"USER REQUEST: '{user_input}'")
    print(f"==========================================\n")

    # Step A: Get structured plan from Supervisor
    prompt = f"{SYSTEM_PROMPT}\n\nUser Input: {user_input}"
    plan: RoutingPlan = supervisor_router.invoke(prompt)

    print(f"--- [Supervisor Plan Generated] ---")
    for idx, t in enumerate(plan.tasks, 1):
        print(f" Task {idx}: Target Agent = '{t.agent}' | Sub-prompt = '{t.task}'")
    print("-" * 45 + "\n")

    execution_results = []
    
    # Step B: Run sub-agents & execute their requested tools
    for t in plan.tasks:
        print(f"--> Delegating to [{t.agent.upper()} AGENT]...")
        
        if t.agent == "lighting":
            agent_response = run_lighting_agent(t.task)
        elif t.agent == "climate":
            agent_response = run_climate_agent(t.task)
        elif t.agent == "security":
            agent_response = run_security_agent(t.task)
        else:
            continue

        # Step C: Execute tool calls generated by sub-agent
        if agent_response.tool_calls:
            tool_outputs = execute_tool_calls(agent_response.tool_calls)
        else:
            tool_outputs = ["No tool call generated."]

        execution_results.append({
            "agent": t.agent,
            "sub_task": t.task,
            "execution_outputs": tool_outputs
        })

    # Step D: Fetch live updated home state
    current_home_state = home_manager.get_all_states()

    return {
        "execution_results": execution_results,
        "updated_home_state": current_home_state
    }